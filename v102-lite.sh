STAMP=$(date +%Y%m%d-%H%M%S)
BACKUP=".git/GOLD-PULSE-before-v10.2.1-lite-$STAMP.tar.gz"
PATCH_FILE=$(mktemp --suffix=.tar.gz)
cleanup(){ rm -f "$PATCH_FILE"; }
trap cleanup EXIT

say "1/8 สำรองเวอร์ชันเดิมไว้ที่ $BACKUP"
tar -czf "$BACKUP" \
  .env.example CHANGELOG.md FILELIST.txt README.md package.json \
  app/layout.js app/page.js app/api/gold/route.js app/api/health/route.js app/api/scan/route.js \
  lib/config.ts lib/alerts.ts lib/core/pulse-engine.js \
  public/manifest.webmanifest public/sw.js \
  scripts/static-check.mjs scripts/test-v10.mjs scripts/test-v10-integration.mjs \
  2>/dev/null || true

