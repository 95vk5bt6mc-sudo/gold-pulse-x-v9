[[ "$CURRENT_VERSION" == "10.0.0" || "$CURRENT_VERSION" == "10.1.0" ]] || \
  fail "ตัวอัปเดตนี้รองรับ v10.0.0 หรือ v10.1.0 เท่านั้น (พบ $CURRENT_VERSION)"

